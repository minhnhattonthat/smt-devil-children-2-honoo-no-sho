"""Write docs/names.md: every translated name field (demon / skill / item / ability...) JP -> EN, for translators.
python -X utf8 tools/harvest.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATS = [(0x2BADFA, 0x2C32C8, 'Demons'), (0x2C32C8, 0x2C5BE8, 'Skills'), (0x2C5BE8, 0x2C8B68, 'Items'),
        (0x2C9BF8, 0x2CA400, 'Combo skills'), (0x2CA400, 0x2CD338, 'Enemy/NPC records'), (0x2CD338, 0x2CE000, 'Passive abilities')]


def main():
    es = json.load(open(ROOT / 'script/names.json', encoding='utf-8'))
    out = ['# Names (harvested from script/names.json; binding spellings)\n',
           'Use these exact spellings in dialogue and descriptions. Generated by tools/harvest.py.\n']
    for lo, hi, name in CATS:
        seen = set()
        rows = []
        for e in es:
            o = int(e['off'], 16)
            if lo <= o < hi and e.get('en') and e['jp'] not in seen:
                seen.add(e['jp'])
                rows.append('%s = %s' % (e['jp'], e['en']))
        out.append('\n## %s\n' % name)
        out.append('; '.join(rows) + '\n')
    (ROOT / 'docs/names.md').write_text(''.join(out), encoding='utf-8', newline='\n')
    print('docs/names.md written')


if __name__ == '__main__':
    main()
